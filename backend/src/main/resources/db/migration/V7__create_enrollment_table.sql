CREATE TABLE enrollment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  course_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  enrolled_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES app_user (id) ON DELETE CASCADE,
  CONSTRAINT fk_enrollment_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
  CONSTRAINT uk_enrollment_student_course UNIQUE (student_id, course_id),
  CONSTRAINT chk_enrollment_status CHECK (
    status IN ('ACTIVE', 'CANCELLED', 'COMPLETED')
  )
);

CREATE INDEX idx_enrollment_student_id ON enrollment (student_id);

CREATE INDEX idx_enrollment_course_id ON enrollment (course_id);

CREATE INDEX idx_enrollment_status ON enrollment (status);
