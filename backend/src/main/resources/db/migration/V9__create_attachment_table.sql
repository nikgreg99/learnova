
CREATE TABLE attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_filename VARCHAR(255) NOT NULL,
    storage_key VARCHAR(1024) NOT NULL UNIQUE,
    content_type VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL,
    uploaded_by VARCHAR(255) NOT NULL,
    course_id BIGINT,
    lesson_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_attachment_course
        FOREIGN KEY (course_id) REFERENCES course (id),

    CONSTRAINT fk_attachment_lesson
        FOREIGN KEY (lesson_id) REFERENCES lesson (id),

    CONSTRAINT chk_attachment_parent
        CHECK (
            (course_id IS NOT NULL AND lesson_id IS NULL)
            OR
            (course_id IS NULL AND lesson_id IS NOT NULL)
        ),

    CONSTRAINT chk_attachment_size
        CHECK (size_bytes >= 0)
);

CREATE INDEX idx_attachment_course_id
    ON attachment (course_id);

CREATE INDEX idx_attachment_lesson_id
    ON attachment (lesson_id);
