CREATE TABLE rating (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  course_id BIGINT,
  lesson_id BIGINT,
  rating INTEGER NOT NULL,
  review TEXT,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rating_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
  CONSTRAINT fk_rating_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
  CONSTRAINT fk_rating_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE,
  CONSTRAINT chk_rating_value CHECK (
    rating >= 1
    AND rating <= 5
  ),
  CONSTRAINT chk_rating_target CHECK (
    (
      course_id IS NOT NULL
      AND lesson_id IS NULL
    )
    OR (
      course_id IS NULL
      AND lesson_id IS NOT NULL
    )
  ),
  CONSTRAINT uk_rating_user_course UNIQUE (user_id, course_id),
  CONSTRAINT uk_rating_user_lesson UNIQUE (user_id, lesson_id)
);

CREATE INDEX idx_rating_course_id ON rating (course_id);

CREATE INDEX idx_rating_lesson_id ON rating (lesson_id);

CREATE INDEX idx_rating_user_id ON rating (user_id);
