CREATE TABLE quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    passing_score INTEGER NOT NULL DEFAULT 70,
    max_attempts INTEGER,
    time_limit_minutes INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_quiz_course
        FOREIGN KEY (course_id)
        REFERENCES course (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_quiz_passing_score
        CHECK (passing_score >= 0 AND passing_score <= 100),

    CONSTRAINT chk_quiz_max_attempts
        CHECK (max_attempts IS NULL OR max_attempts > 0),

    CONSTRAINT chk_quiz_time_limit_minutes
        CHECK (time_limit_minutes IS NULL OR time_limit_minutes > 0)
);

CREATE INDEX idx_quiz_course_id ON quiz (course_id);

CREATE TABLE quiz_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    text TEXT NOT NULL,
    type VARCHAR(30) NOT NULL,
    points INTEGER NOT NULL DEFAULT 1,
    position INTEGER NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_quiz_question_quiz
        FOREIGN KEY (quiz_id)
        REFERENCES quiz (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_quiz_question_type
        CHECK (type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE', 'TRUE_FALSE')),

    CONSTRAINT chk_quiz_question_points
        CHECK (points > 0),

    CONSTRAINT chk_quiz_question_position
        CHECK (position > 0),

    CONSTRAINT uk_quiz_question_quiz_position
        UNIQUE (quiz_id, position)
);

CREATE INDEX idx_quiz_question_quiz_id ON quiz_question (quiz_id);

CREATE TABLE quiz_answer_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL,
    text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    position INTEGER NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_quiz_answer_option_question
        FOREIGN KEY (question_id)
        REFERENCES quiz_question (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_quiz_answer_option_position
        CHECK (position > 0)
);

CREATE INDEX idx_quiz_answer_option_question_id ON quiz_answer_option (question_id);

CREATE TABLE quiz_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    attempt_number INTEGER NOT NULL,
    score NUMERIC(5, 2),
    earned_points INTEGER,
    total_points INTEGER,
    passed BOOLEAN,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP(6),

    CONSTRAINT fk_quiz_attempt_quiz
        FOREIGN KEY (quiz_id)
        REFERENCES quiz (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_quiz_attempt_user
        FOREIGN KEY (user_id)
        REFERENCES app_user (id)
        ON DELETE CASCADE,

    CONSTRAINT uk_quiz_attempt_quiz_user_attempt
        UNIQUE (quiz_id, user_id, attempt_number),

    CONSTRAINT chk_quiz_attempt_number
        CHECK (attempt_number > 0),

    CONSTRAINT chk_quiz_attempt_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'TIMED_OUT'))
);

CREATE INDEX idx_quiz_attempt_quiz_id ON quiz_attempt (quiz_id);
CREATE INDEX idx_quiz_attempt_user_id ON quiz_attempt (user_id);

CREATE TABLE quiz_attempt_answer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    selected_option_id BIGINT NOT NULL,

    CONSTRAINT fk_quiz_attempt_answer_attempt
        FOREIGN KEY (attempt_id)
        REFERENCES quiz_attempt (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_quiz_attempt_answer_question
        FOREIGN KEY (question_id)
        REFERENCES quiz_question (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_quiz_attempt_answer_option
        FOREIGN KEY (selected_option_id)
        REFERENCES quiz_answer_option (id)
        ON DELETE CASCADE,

    CONSTRAINT uk_quiz_attempt_answer
        UNIQUE (attempt_id, question_id, selected_option_id)
);

CREATE INDEX idx_quiz_attempt_answer_attempt_id ON quiz_attempt_answer (attempt_id);
